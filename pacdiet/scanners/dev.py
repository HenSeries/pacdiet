#: Never offer artifacts nested inside these -- they belong to a toolchain,
#: not to one of the user's projects, and are handled above.
ARTIFACT_EXCLUDE_PARTS = {
    ".cache", ".local", ".cargo", ".gradle", ".npm", ".pub-cache", ".rustup",
    ".nvm", "go", ".m2", "node_modules", "site-packages", ".git", "Sdk",
}

MIN_SIZE = 10 * 1024 * 1024
IDLE_DAYS = 14


def scan_toolchain() -> list[Finding]:
    present = []
    for rel, label, detail, risk in TOOLCHAIN:
        path = HOME / rel
        if path.is_dir():
            present.append((path, label, detail, risk))
    sizes = dir_sizes([p for p, *_ in present], timeout=900)

    findings = []
    for path, label, detail, risk in present:
        size = sizes.get(str(path), 0)
        if size < MIN_SIZE:
            continue
        findings.append(Finding(
            key=f"tool-{path.relative_to(HOME).as_posix().replace('/', '-')}",
            label=f"{label} (~/{path.relative_to(HOME)})",
            detail=detail,
            size=size,
            risk=risk,
            selected=risk is Risk.SAFE,
            action=Action(paths=[str(path)]),
        ))
    return sorted(findings, key=lambda f: f.size, reverse=True)


def _artifact_roots() -> list[Path]:
    """Where to look for project build output: visible folders in $HOME."""
    roots = []
    try:
        for entry in HOME.iterdir():
            if entry.is_dir() and not entry.name.startswith(".") and not entry.is_symlink():
                roots.append(entry)
    except OSError:
        pass
    return roots


def scan_build_artifacts(max_depth: int = 7, timeout: int = 600) -> list[Finding]:
    """Find rebuildable build directories that nobody has touched recently.

    Pruning at each match keeps this tractable even on very large source trees:
    once we see a node_modules we do not walk into it.
    """
    roots = _artifact_roots()
    if not roots:
        return []

    expr: list[str] = ["("]
    for i, name in enumerate(ARTIFACTS):
        if i:
            expr.append("-o")
        expr += ["-name", name]
    expr.append(")")

    cmd = [
        "find", *[str(r) for r in roots],
        "-maxdepth", str(max_depth), "-type", "d", *expr, "-prune", "-print",
    ]
    proc = run(cmd, timeout=timeout)
    partial = proc.returncode == 124

    candidates: list[Path] = []
    for ln in proc.stdout.splitlines():
        if not ln.strip():
            continue
        p = Path(ln)
        if ARTIFACT_EXCLUDE_PARTS & set(p.parts[:-1]):
            continue
        candidates.append(p)

    if not candidates:
        return []

    sizes = dir_sizes(candidates, timeout=900)
    findings = []
    for path in candidates:
        size = sizes.get(str(path), 0)
        if size < MIN_SIZE:
            continue
        idle = mtime_days(path)
        if idle < IDLE_DAYS:
            continue  # an active project; leave it alone
        project = path.parent.name or str(path.parent)
        findings.append(Finding(
            key=f"artifact-{path.as_posix()}",
            label=f"{project}/{path.name}",
            detail=(
                f"{ARTIFACTS.get(path.name, 'Build output.')} "
                f"Idle for {int(idle)} days. Full path: {path}"
            ),
            size=size,
            risk=Risk.REVIEW,
            action=Action(paths=[str(path)]),
        ))
    findings.sort(key=lambda f: f.size, reverse=True)
    if partial:
        findings.insert(0, Finding(
            key="artifact-partial",
            label="(scan hit its time limit — results are incomplete)",
            detail="Your source tree is large. Re-run with a longer limit to see the rest.",
            size=0,
            risk=Risk.CAREFUL,
            action=Action(command=["true"]),
        ))
    return findings


